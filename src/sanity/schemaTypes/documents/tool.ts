import { defineField, defineType } from "sanity";
import { richContentField } from "@/sanity/schemaTypes/fields/richContent";

export const tool = defineType({
  name: "tool",
  title: "Arac",
  type: "document",
  description: "Yapay zeka arac incelemeleri ve detay sayfalari.",
  groups: [
    { name: "editorial", title: "Editoryal" },
    { name: "taxonomy", title: "Baglantilar" },
    { name: "media", title: "Medya" },
    { name: "commercial", title: "Ticari" },
    { name: "trust", title: "Guven" },
    { name: "seo", title: "SEO" },
  ],
  fields: [
    defineField({
      name: "name",
      title: "Tool adi",
      type: "string",
      group: "editorial",
      validation: (rule) => rule.required(),
      description: "Kartlarda ve schema icinde gorunen kisa urun adi.",
    }),
    defineField({
      name: "title",
      title: "Title",
      type: "string",
      group: "editorial",
      validation: (rule) => rule.required(),
      description: "Tarayici sekmesi, Google basligi ve varsayilan sosyal baslik icin kullanilir.",
    }),
    defineField({
      name: "h1",
      title: "H1 override",
      type: "string",
      group: "editorial",
    }),
    defineField({
      name: "slug",
      title: "Slug",
      type: "slug",
      group: "editorial",
      options: {
        source: "name",
        maxLength: 120,
      },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "description",
      title: "Kisa aciklama",
      type: "text",
      rows: 3,
      group: "editorial",
      validation: (rule) => rule.required(),
      description: "Kartlarda, listelemelerde ve sayfa icindeki gorunen kisa ozet alanlarinda kullanilir.",
    }),
    defineField({
      name: "metaDescription",
      title: "Meta aciklama",
      type: "text",
      rows: 3,
      group: "seo",
      validation: (rule) => rule.max(160).warning("Meta aciklama 160 karakteri gecmemeli."),
      description: "Sadece SEO meta aciklamasi icin kullanilir. Bos birakilirsa kisa aciklama kullanilir.",
    }),
    defineField({
      name: "heroIntro",
      title: "Hero girisi",
      type: "text",
      rows: 4,
      group: "editorial",
    }),
    defineField({
      name: "bodyMarkdown",
      title: "Eski MDX govdesi",
      type: "text",
      rows: 24,
      group: "editorial",
      hidden: ({ document }) => !document?.bodyMarkdown,
      description:
        "Sadece daha once MDX'ten tasinmis eski iceriklerde gorunur.",
    }),
    richContentField("body", "Inceleme govdesi"),
    defineField({
      name: "author",
      title: "Yazar",
      type: "reference",
      group: "taxonomy",
      to: [{ type: "author" }],
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "category",
      title: "Kategori",
      type: "reference",
      group: "taxonomy",
      to: [{ type: "category" }],
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "tags",
      title: "Etiketler",
      type: "array",
      group: "taxonomy",
      of: [{ type: "string" }],
      description: "Arama ve filtreleme icin kullanabileceginiz yardimci etiketler.",
    }),
    defineField({
      name: "logo",
      title: "Kucuk logo/icon",
      type: "image",
      group: "media",
      options: {
        hotspot: true,
      },
      fields: [
        defineField({
          name: "alt",
          title: "Alt metni",
          type: "string",
          validation: (rule) => rule.required().warning("Logo alt metni ekleyin."),
        }),
      ],
    }),
    defineField({
      name: "featuredImage",
      title: "One cikarilan gorsel",
      type: "image",
      group: "media",
      options: {
        hotspot: true,
      },
      fields: [
        defineField({
          name: "alt",
          title: "Alt metni",
          type: "string",
          validation: (rule) => rule.required().warning("One cikarilan gorsel icin alt metni ekleyin."),
        }),
      ],
    }),
    defineField({
      name: "screenshots",
      title: "Ekran goruntuleri",
      type: "array",
      group: "media",
      of: [
        defineField({
          name: "screenshot",
          title: "Ekran goruntusu",
          type: "image",
          options: {
            hotspot: true,
          },
          fields: [
            defineField({
              name: "alt",
              title: "Alt metni",
              type: "string",
              validation: (rule) => rule.required().warning("Her ekran goruntusune alt metni ekleyin."),
            }),
            defineField({
              name: "caption",
              title: "Aciklama",
              type: "string",
            }),
          ],
        }),
      ],
    }),
    defineField({
      name: "websiteUrl",
      title: "Resmi website",
      type: "url",
      group: "commercial",
      description: "Tool'un resmi sitesi. CTA butonu bu alani kullanir.",
    }),
    defineField({
      name: "pricing",
      title: "Fiyatlandirma metni",
      type: "string",
      group: "commercial",
      description: "Gorunen fiyatlama ozeti. Ornek: Ucretsiz plan var, Pro 199 TL/ay",
    }),
    defineField({
      name: "hasFreeTier",
      title: "Ucretsiz plan var",
      type: "boolean",
      group: "commercial",
      initialValue: false,
    }),
    defineField({
      name: "priceAmount",
      title: "Baslangic fiyat",
      type: "number",
      group: "commercial",
    }),
    defineField({
      name: "priceCurrency",
      title: "Para birimi",
      type: "string",
      group: "commercial",
      initialValue: "USD",
    }),
    defineField({
      name: "isTRSupported",
      title: "Turkce destek var",
      type: "boolean",
      group: "commercial",
      initialValue: false,
    }),
    defineField({
      name: "pros",
      title: "Arti yonler",
      type: "array",
      group: "trust",
      of: [{ type: "string" }],
    }),
    defineField({
      name: "cons",
      title: "Eksi yonler",
      type: "array",
      group: "trust",
      of: [{ type: "string" }],
    }),
    defineField({
      name: "faqs",
      title: "SSS",
      type: "array",
      group: "trust",
      of: [{ type: "faqItem" }],
      validation: (rule) => rule.required().min(1).error("Her arac iceriginde en az 1 SSS maddesi olmali."),
    }),
    defineField({
      name: "datePublished",
      title: "Yayin tarihi",
      type: "datetime",
      group: "trust",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "dateModified",
      title: "Guncelleme tarihi",
      type: "datetime",
      group: "trust",
    }),
    defineField({
      name: "seo",
      title: "SEO",
      type: "seoMetadata",
      group: "seo",
      description: "Sadece canonical veya noindex gibi istisnai durumlarda kullanin.",
    }),
  ],
  preview: {
    select: {
      title: "name",
      subtitle: "description",
      media: "logo",
    },
  },
});
