import { defineField, defineType } from "sanity";
import { richContentField } from "@/sanity/schemaTypes/fields/richContent";
import { slugifyTurkish } from "@/sanity/schemaTypes/utils/slugify";

export const comparison = defineType({
  name: "comparison",
  title: "Karşılaştırma",
  type: "document",
  description: "Yapay zeka araçlarını senaryo bazlı karşılaştıran editör içerikleri.",
  groups: [
    { name: "editorial", title: "Editoryal" },
    { name: "taxonomy", title: "Bağlantılar" },
    { name: "media", title: "Medya" },
    { name: "trust", title: "Güven" },
    { name: "seo", title: "SEO" },
  ],
  fields: [
    defineField({
      name: "title",
      title: "Title",
      type: "string",
      group: "editorial",
      validation: (rule) => rule.required(),
      description: "Tarayıcı sekmesi, Google başlığı ve varsayılan sosyal başlık için kullanılır.",
    }),
    defineField({
      name: "h1",
      title: "H1 override",
      type: "string",
      group: "editorial",
    }),
    defineField({
      name: "slug",
      title: "Slug",
      type: "slug",
      group: "editorial",
      options: {
        source: "title",
        maxLength: 120,
        slugify: (input) => slugifyTurkish(input),
      },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "description",
      title: "Kısa açıklama",
      type: "text",
      rows: 3,
      group: "editorial",
      validation: (rule) => rule.required(),
      description: "Kartlarda, listelemelerde ve sayfa içindeki görünen kısa özet alanlarında kullanılır.",
    }),
    defineField({
      name: "metaDescription",
      title: "Meta açıklama",
      type: "text",
      rows: 3,
      group: "seo",
      validation: (rule) => rule.max(160).warning("Meta açıklama 160 karakteri geçmemeli."),
      description: "Sadece SEO meta açıklaması için kullanılır. Boş bırakılırsa kısa açıklama kullanılır.",
    }),
    defineField({
      name: "heroIntro",
      title: "Hero girişi",
      type: "text",
      rows: 4,
      group: "editorial",
    }),
    defineField({
      name: "verdict",
      title: "Kısa karar özeti",
      type: "text",
      rows: 3,
      group: "editorial",
      description: "Sayfa üstünde ve liste kartlarında kullanılabilecek kısa sonuç metni.",
    }),
    defineField({
      name: "bodyMarkdown",
      title: "Eski MDX gövdesi",
      type: "text",
      rows: 24,
      group: "editorial",
      hidden: ({ document }) => !document?.bodyMarkdown,
      description: "Sadece daha önce MDX'ten taşınmış eski içeriklerde görünür.",
    }),
    richContentField("body", "Karşılaştırma gövdesi"),
    defineField({
      name: "author",
      title: "Yazar",
      type: "reference",
      group: "taxonomy",
      to: [{ type: "author" }],
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "category",
      title: "Kategori",
      type: "reference",
      group: "taxonomy",
      to: [{ type: "category" }],
      validation: (rule) => rule.required().error("Her karşılaştırma bir kategoriye bağlı olmalı."),
    }),
    defineField({
      name: "toolNames",
      title: "Karşılaştırılan araç adları",
      type: "array",
      group: "taxonomy",
      of: [{ type: "string" }],
      validation: (rule) => rule.required().min(2).error("En az 2 araç adı girin."),
      description: "Sayfada karşılaştırılan araçların görünen adları.",
    }),
    defineField({
      name: "comparedTools",
      title: "İlgili araç incelemeleri",
      type: "array",
      group: "taxonomy",
      of: [{ type: "reference", to: [{ type: "tool" }] }],
      validation: (rule) =>
        rule.min(1).warning("Sitede incelemesi olan en az bir aracı bağlayın; iç link ve schema daha güçlü olur."),
      description: "Sitede incelemesi olan araçları bağlayarak iç linkleri güçlendirin.",
    }),
    defineField({
      name: "featuredImage",
      title: "Öne çıkarılan görsel",
      type: "image",
      group: "media",
      options: {
        hotspot: true,
      },
      fields: [
        defineField({
          name: "alt",
          title: "Alt metni",
          type: "string",
          validation: (rule) => rule.required().warning("Öne çıkarılan görsel için alt metni ekleyin."),
        }),
      ],
    }),
    defineField({
      name: "sources",
      title: "Kaynaklar",
      type: "array",
      group: "trust",
      of: [{ type: "sourceItem" }],
      description: "Bu karşılaştırmada kullanılan resmî kaynak URL'leri.",
    }),
    defineField({
      name: "faqs",
      title: "SSS",
      type: "array",
      group: "trust",
      of: [{ type: "faqItem" }],
      validation: (rule) => rule.required().min(1).error("Her karşılaştırma içeriğinde en az 1 SSS maddesi olmalı."),
    }),
    defineField({
      name: "datePublished",
      title: "Yayın tarihi",
      type: "datetime",
      group: "trust",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "dateModified",
      title: "Güncelleme tarihi",
      type: "datetime",
      group: "trust",
    }),
    defineField({
      name: "lastVerified",
      title: "Son doğrulama tarihi",
      type: "date",
      group: "trust",
      validation: (rule) => rule.required().error("Her karşılaştırmada son doğrulama tarihi girilmeli."),
      description: "İçeriğin teknik ve ticari sinyallerinin son kontrol tarihi.",
    }),
    defineField({
      name: "verificationNotes",
      title: "Doğrulama notları",
      type: "text",
      rows: 3,
      group: "trust",
      description: "İçeriğin hangi kaynaklar veya sinyaller üzerinden doğrulandığına dair iç not.",
    }),
    defineField({
      name: "seo",
      title: "SEO",
      type: "seoMetadata",
      group: "seo",
      description: "Sadece canonical veya noindex gibi istisnai durumlarda kullanın.",
    }),
  ],
  preview: {
    select: {
      title: "title",
      subtitle: "verdict",
      media: "featuredImage",
    },
  },
});
